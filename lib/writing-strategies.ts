export const FUNCTION_DESCRIPTION_RULES = `功能描述写作策略：
只描述目录标题对应的一个已拆分功能，回答“功能怎么用、系统怎么做”。
根据已确认的信息说明服务对象、触发动作、处理过程和输出结果；
缺少某一环节的依据时，不要臆测补齐；允许正文少于目标字数，并自然结束。
默认只输出可进入申报书的正文，不要输出“待确认”、问题清单、材料缺口、写作说明或自我解释。
只有当用户在补充要求中明确要求“列出待确认事项”时，才在正文后用不超过 3 条的简短条目列出。
使用简短自然段，按功能实际运作顺序组织；不强制拆成小节，不自行命名子功能或扩展相邻节点。
不要写项目背景、建设意义、行业痛点或必要性，不使用“破解、促进、赋能”等宏观价值叙述来填充正文。
不将行业惯例或技术常识写成已确认的项目能力；可以改写和衔接已有事实，不增加未经确认的角色权限、审批规则、字段、时限、接口、技术和子模块。
目标字数仅作参考，材料不足时允许少于目标，不用建议性设计凑字数。润色时也须保持单功能边界，不扩写新事实。
只描述当前目录节点对应的功能。可以说明与上下游环节的衔接关系，但不得展开相邻节点的具体功能、流程或规则。`;

const HIGH_RISK_CHAPTER_RULES: Record<string, string> = {
  basis: `建设必要性与政策依据边界：
只使用用户上传或已确认的政策材料；不得编造政策名称、文号、发布时间、具体要求或适用结论。
应说明政策要求与当前项目的对应关系，不进行无关政策堆砌；结合可确认的甲方现状说明建设必要性，并与建设目标衔接。`,
  innovation: `创新与特色边界：
只能从已确认的流程、治理、协同、技术方案、业务场景或服务模式中提炼特色；不得自行增加未确认技术能力。
禁止使用“全国首创”“国际领先”“行业第一”等无法证明的表述，也不得将一般行业做法写成项目独有创新。`,
  budget: `投资估算 / 预算说明边界：
只能对用户已提供并确认的预算数据进行结构整理、分类说明和文字表达。
不得自行生成项目总投资、软硬件金额、设备数量、人工成本或其他具体数据；预算信息不足时，应明确需要用户补充相关资料，不得推测或估算。`,
};

export function buildGenerationSystemPrompt(item: OutlineItem): string {
  const chapterRule = HIGH_RISK_CHAPTER_RULES[item.promptKey || item.id];
  return FACT_SAFETY_RULES
    + (getWritingType(item) === "function_description" ? `\n\n${FUNCTION_DESCRIPTION_RULES}` : "")
    + (chapterRule ? `\n\n${chapterRule}` : "");
}
